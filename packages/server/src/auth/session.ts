// `human` sessions. A row is inserted in exactly one function, `issueSession`,
// and that function is only called after a verified passkey assertion or
// registration: there is no code path from an `agent` credential to here (I6).

import type { DeviceId, PrincipalId } from '@sudare/protocol'
import { hours, type Env } from '../env'
import { randomToken, sha256 } from '../util'

export type Session = { principal: PrincipalId; kind: 'web' | 'plugin'; device: DeviceId | null; expires: number; via: 'cookie' | 'bearer' }

const COOKIE = '__Host-sudare'
const PREFIX = 'sds'

import type { PasskeyProof } from './passkey'

export const issueSession = async (
  env: Env, proof: PasskeyProof, kind: Session['kind'], device: DeviceId | null,
): Promise<{ token: string; expires: number }> => {
  const token = randomToken(PREFIX)
  const ttl = kind === 'web' ? hours(env.WEB_SESSION_HOURS, 168) : hours(env.PLUGIN_SESSION_HOURS, 8)
  const expires = Date.now() + ttl * 3_600_000
  await env.DB.prepare(`INSERT INTO sessions (hash, principal, kind, device, created_at, expires_at) VALUES (?, ?, ?, ?, ?, ?)`)
    .bind(await sha256(token), proof.principal, kind, device, Date.now(), expires).run()
  return { token, expires }
}

/**
 * The plugin flow: the session's secret was generated by the plugin and only
 * its hash ever reached the server. The passkey ceremony turns that hash into
 * a session; the plugin then presents the secret it already holds.
 */
export const adoptSession = async (
  env: Env, proof: PasskeyProof, hash: string, kind: Session['kind'], device: DeviceId | null, ttlHours?: number,
): Promise<{ expires: number }> => {
  const ttl = ttlHours ?? (kind === 'web' ? hours(env.WEB_SESSION_HOURS, 168) : hours(env.PLUGIN_SESSION_HOURS, 8))
  const expires = Date.now() + ttl * 3_600_000
  await env.DB.prepare(`INSERT INTO sessions (hash, principal, kind, device, created_at, expires_at) VALUES (?, ?, ?, ?, ?, ?)`)
    .bind(hash, proof.principal, kind, device, Date.now(), expires).run()
  return { expires }
}

export const sessionCookie = (token: string, expires: number): string =>
  `${COOKIE}=${token}; Path=/; HttpOnly; Secure; SameSite=Lax; Expires=${new Date(expires).toUTCString()}`

export const clearCookie = (): string => `${COOKIE}=; Path=/; HttpOnly; Secure; SameSite=Lax; Max-Age=0`

const cookieToken = (request: Request): string | null => {
  const header = request.headers.get('Cookie') ?? ''
  const hit = header.split(/;\s*/).find((c) => c.startsWith(`${COOKIE}=`))
  return hit ? hit.slice(COOKIE.length + 1) : null
}

const bearerToken = (request: Request): string | null => {
  const header = request.headers.get('Authorization') ?? ''
  return header.startsWith('Bearer ') ? header.slice(7).trim() : null
}

/** Resolves the `human` session on a request, if any. Agent tokens never match: different prefix, different table. */
export const readSession = async (env: Env, request: Request): Promise<Session | null> => {
  const bearer = bearerToken(request)
  const token = bearer ?? cookieToken(request)
  if (!token || !token.startsWith(`${PREFIX}_`)) return null
  const row = await env.DB.prepare(`SELECT principal, kind, device, expires_at FROM sessions WHERE hash = ?`)
    .bind(await sha256(token)).first<{ principal: PrincipalId; kind: Session['kind']; device: DeviceId | null; expires_at: number }>()
  if (!row || row.expires_at <= Date.now()) return null
  return { principal: row.principal, kind: row.kind, device: row.device, expires: row.expires_at, via: bearer ? 'bearer' : 'cookie' }
}

export const endSession = async (env: Env, request: Request): Promise<void> => {
  const token = bearerToken(request) ?? cookieToken(request)
  if (token) await env.DB.prepare(`DELETE FROM sessions WHERE hash = ?`).bind(await sha256(token)).run()
}

/** Revoking a device also ends any plugin session that was linked from it. */
export const endDeviceSessions = (env: Env, device: DeviceId) =>
  env.DB.prepare(`DELETE FROM sessions WHERE device = ?`).bind(device).run()
