const dicts: Record<Lang, Record<Key, string>> = { en, zh }

export const hasKey = (key: string): key is Key => Object.hasOwn(en, key)

export const t = (key: Key, vars?: Record<string, string | number>): string => {
  const text = dicts[getState().lang][key]
  return vars ? text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole)) : text
}
